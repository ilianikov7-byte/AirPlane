int _write(int fd, char *ptr, int len)   // makes printf() go to USB
{
	uint32_t start = HAL_GetTick();
	while (CDC_Transmit_FS((uint8_t*) ptr, len) == USBD_BUSY) {
		if (HAL_GetTick() - start > 10)
			return 0;
	}
	return len;
}

static uint8_t imu_read_reg(uint8_t reg) {
	uint8_t tx[2] = { reg | 0x80, 0x00 };   // bit 7 = 1 means read
	uint8_t rx[2] = { 0, 0 };
	IMU_CS_LOW();
	HAL_SPI_TransmitReceive(&hspi1, tx, rx, 2, 10);
	IMU_CS_HIGH();
	return rx[1];
}

static void imu_write_reg(uint8_t reg, uint8_t value) {
	uint8_t tx[2] = { reg & 0x7F, value };  // bit 7 = 0 means write
	IMU_CS_LOW();
	HAL_SPI_Transmit(&hspi1, tx, 2, 10);
	IMU_CS_HIGH();
}

static void imu_read_burst(uint8_t reg, uint8_t *buf, uint16_t len)
{
    uint8_t tx[13] = {0};
    uint8_t rx[13] = {0};

    if (len > 12) len = 12;          // <-- new: protects the buffers

    tx[0] = reg | 0x80;   // read command

    IMU_CS_LOW();
    HAL_SPI_TransmitReceive(&hspi1, tx, rx, len + 1, 100);
    IMU_CS_HIGH();

    for (uint16_t i = 0; i < len; i++)
    {
        buf[i] = rx[i + 1];
    }
}
static int16_t imu_read_axis(uint8_t reg_high)
{
    uint8_t b[2];
    imu_read_burst(reg_high, b, 2);
    return (int16_t)((b[0] << 8) | b[1]);
}
